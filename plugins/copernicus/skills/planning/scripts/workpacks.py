def cmd_init(args: argparse.Namespace) -> None:
    bundle = Path(args.bundle)
    if "\n" in args.title or not args.title.strip():
        raise PlanningError("title must be one non-empty line")
    if args.mode not in {"workpacks", "discovery"}:
        raise PlanningError("init mode must be workpacks or discovery")
    bundle.mkdir(parents=True, exist_ok=False)
    (bundle / "workpacks").mkdir()
    today = date.today().isoformat()
    write_new(bundle / "design.md", design_template(args.title.strip(), args.mode, today))
    write_new(bundle / "workpacks/WP-001.md", workpack_template(today))
    write_new(
        bundle / "log.md",
        f"# Planning log\n\n## {today}\n\n- Initialized `{args.mode}` bundle.\n",
    )
    cmd_index(argparse.Namespace(bundle=str(bundle), write=True))
    print(bundle.resolve())


def root_index(design: dict, workpacks: dict[str, dict]) -> str:
    counts = Counter(meta["status"] for meta in workpacks.values())
    summary = ", ".join(f"{status}: {counts[status]}" for status in sorted(counts))
    return f"""{GENERATED}
# {design['title']}

{design['description']}

- [Design](design.md)
- [Workpacks](workpacks/index.md)
- [Planning log](log.md)

## Status

- Design: `{design['status']}`
- Workpacks: {summary}
"""


def workpack_index(workpacks: dict[str, dict], waves: list[list[str]]) -> str:
    lines = [GENERATED, "# Workpacks", "", "Dependency waves are derived from `depends_on`.", ""]
    for number, wave in enumerate(waves, 1):
        lines.extend([f"## Wave {number}", ""])
        for identifier in sorted(
            wave, key=lambda item: (PRIORITIES[workpacks[item]["priority"]], item)
        ):
            meta = workpacks[identifier]
            lines.append(
                f"- [{identifier}: {meta['title']}]({identifier}.md) — "
                f"`{meta['status']}` / `{meta['priority']}` — {meta['description']}"
            )
        lines.append("")
    return "\n".join(lines)


def cmd_validate(args: argparse.Namespace) -> None:
    load_bundle(
        Path(args.bundle),
        implementation_ready=args.implementation_ready,
        repo_root=Path(args.repo_root) if args.repo_root else None,
    )
    print("OK")


def cmd_index(args: argparse.Namespace) -> None:
    if not args.write:
        raise PlanningError("index is non-mutating unless --write is explicit")
    bundle = Path(args.bundle)
    design, workpacks, waves = load_bundle(bundle)
    write_generated(bundle / "index.md", root_index(design, workpacks))
    write_generated(bundle / "workpacks/index.md", workpack_index(workpacks, waves))
    print("OK")


def cmd_next(args: argparse.Namespace) -> None:
    _, workpacks, _ = load_bundle(Path(args.bundle))
    ready = [
        identifier
        for identifier, meta in workpacks.items()
        if meta["status"] == "ready"
        and all(workpacks[dependency]["status"] == "done" for dependency in meta["depends_on"])
    ]
    ready.sort(key=lambda item: (PRIORITIES[workpacks[item]["priority"]], item))
    print("\n".join(ready) if ready else "none")


def parser() -> argparse.ArgumentParser:
    command = argparse.ArgumentParser(description=__doc__)
    sub = command.add_subparsers(dest="command", required=True)

    init = sub.add_parser("init", help="create a new workpack bundle without overwriting")
    init.add_argument("bundle")
    init.add_argument("--title", required=True)
    init.add_argument("--mode", choices=("workpacks", "discovery"), default="workpacks")
    init.set_defaults(func=cmd_init)

    validate = sub.add_parser("validate", help="validate structure, graph, paths, and readiness")
    validate.add_argument("bundle")
    validate.add_argument("--implementation-ready", action="store_true")
    validate.add_argument("--repo-root")
    validate.set_defaults(func=cmd_validate)

    index = sub.add_parser("index", help="regenerate reserved navigation files")
    index.add_argument("bundle")
    index.add_argument("--write", action="store_true")
    index.set_defaults(func=cmd_index)

    next_parser = sub.add_parser("next", help="print ready workpacks whose dependencies are done")
    next_parser.add_argument("bundle")
    next_parser.set_defaults(func=cmd_next)
    return command


def main(argv: list[str] | None = None) -> int:
    args = parser().parse_args(argv)
    try:
        args.func(args)
        return 0
    except (OSError, PlanningError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
